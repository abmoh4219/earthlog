/** Feed sections that settle the topic outright (DW's dc:subject, AllAfrica's categories). */
const SECTIONS: [RegExp, Topic][] = [
  [/^sport|football|soccer/i, "sports"],
  [/environment|climate/i, "climate"],
  [/^science|space/i, "science"],
  [/technology|^tech/i, "tech"],
  [/^health/i, "health"],
  [/^business|econom|finance|markets/i, "business"],
  [/^culture|arts|entertainment|music|film/i, "culture"],
  [/conflict|war|military/i, "conflict"],
];

function votes(title: string): Map<Topic, number> {
  const text = ` ${title.toLowerCase().replace(/[’']/g, "'")} `;
  const out = new Map<Topic, number>();
  for (const [topic, phrases] of RULES) {
    let n = 0;
    for (const phrase of phrases) {
      const whole = phrase.endsWith("$");
      const p = whole ? phrase.slice(0, -1) : phrase;
      // Word start: "war" must not match "award" or "toward"; trailing letters are allowed.
      for (let i = text.indexOf(p); i > 0; i = text.indexOf(p, i + 1)) {
        if (/[a-z0-9]/.test(text[i - 1] ?? "")) continue;
        // Short words (and "$" phrases) must end there too, plural allowed: "war" is not
        // "warning", "author" is not "authorities".
        const after = text.slice(i + p.length, i + p.length + 2);
        if ((whole || p.length <= 4) && /^[a-z0-9]/.test(after) && !/^s[^a-z0-9]/.test(after))
          continue;
        n++;
        break;
      }
    }
    if (n) out.set(topic, n);
  }
  return out;
}

export function topicOf(items: { title: string; section?: string | undefined }[]): Topic {
  const tally = new Map<Topic, number>();
  for (const { title, section } of items) {
    const fromSection = section ? SECTIONS.find(([re]) => re.test(section))?.[1] : undefined;
    if (fromSection) tally.set(fromSection, (tally.get(fromSection) ?? 0) + 2);
    for (const [t, n] of votes(title)) tally.set(t, (tally.get(t) ?? 0) + n);
  }
  const order = RULES.map(([t]) => t);
  const best = [...tally.entries()].sort(
    (a, b) => b[1] - a[1] || order.indexOf(a[0]) - order.indexOf(b[0]),
  )[0];
  return best?.[0] ?? "world";
}
